Future<void> _pump(WidgetTester tester) async {
  await tester.pumpWidget(
    const MaterialApp(
      locale: Locale('tr'),
      localizationsDelegates: AppLocalizations.localizationsDelegates,
      supportedLocales: AppLocalizations.supportedLocales,
      home: SourcesScreen(),
    ),
  );
  await tester.pumpAndSettle();
}

List<int> _runes(WidgetTester tester, String key) =>
    tester.widget<Text>(find.byKey(Key(key))).data!.runes.toList();

void main() {
  testWidgets('headers match the spec byte for byte', (tester) async {
    await _pump(tester);
    for (var i = 0; i < 4; i++) {
      expect(
        _runes(tester, 'sources-header-$i'),
        _expected[2 * i],
        reason: 'header $i',
      );
    }
    expect(find.byKey(const Key('sources-header-4')), findsNothing);
  });

  testWidgets('texts match the spec byte for byte', (tester) async {
    await _pump(tester);
    for (var i = 0; i < 4; i++) {
      // Below the fold on a small test screen: bring each into the tree.
      await tester.scrollUntilVisible(
        find.byKey(Key('sources-text-$i')),
        100,
        scrollable: find.byType(Scrollable),
      );
      expect(
        _runes(tester, 'sources-text-$i'),
        _expected[2 * i + 1],
        reason: 'text $i',
      );
    }
    expect(find.byKey(const Key('sources-text-4')), findsNothing);
  });
}
